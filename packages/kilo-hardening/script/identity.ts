#!/usr/bin/env bun
/**
 * Gives the packaged extension its own identity so it installs beside upstream Kilo Code, never
 * receives a Marketplace update meant for it, and never shares its settings, commands or views.
 *
 * Rewrites, in an extension directory:
 *   - package.json: publisher, name, displayName; removes commands, menus and keybindings for
 *     features this build does not ship; renames the `kilo-code.` namespace
 *   - package.nls*.json and dist/**\/*.js: the same namespace rename, so code and manifest agree
 *
 * Usage: bun script/identity.ts <extension-dir> [--restore]
 * The original package.json is saved as package.json.upstream and put back by --restore.
 */
import { copyFileSync, existsSync, readFileSync, readdirSync, renameSync, statSync, writeFileSync } from "node:fs"
import path from "node:path"
import { config, type Config } from "../src/config"

const UPSTREAM = { publisher: "kilocode", name: "kilo-code" }

/** Command IDs (upstream names) removed from the manifest. Their handlers are no-ops at runtime. */
export function removed(cfg: Config) {
  const ids = [
    "kilo-code.new.marketplaceButtonClicked",
    "kilo-code.new.sidebarTitle.marketplaceButtonClicked",
    "kilo-code.new.profileButtonClicked",
    "kilo-code.new.sidebarTitle.profileButtonClicked",
  ]
  if (!cfg.features.autocomplete)
    ids.push(
      "kilo-code.new.autocomplete.generateSuggestions",
      "kilo-code.new.autocomplete.cancelSuggestions",
      "kilo-code.new.autocomplete.nextEdit.acceptOrJump",
      "kilo-code.new.autocomplete.nextEdit.dismiss",
    )
  return new Set(ids)
}

/** Renames every upstream identifier form in a text (manifest, NLS file or bundled JS). */
export function rename(text: string, cfg: Config = config) {
  const name = cfg.identity.name
  return text
    .replaceAll(`${UPSTREAM.publisher}.${UPSTREAM.name}`, `${cfg.identity.publisher}.${name}`)
    .replaceAll(`${UPSTREAM.name}-ActivityBar`, `${name}-ActivityBar`)
    .replace(/(?<![\w@/-])kilo-code\.(?=[A-Za-z])/g, `${name}.`)
    // The same prefix inside regex literals, e.g. /^kilo-code\.new\.(\w+)Panel$/
    .replace(/(?<![\w@/-])kilo-code\\\.(?=[A-Za-z])/g, `${name}\\.`)
}

type Manifest = {
  publisher: string
  name: string
  displayName: string
  contributes?: {
    commands?: { command: string }[]
    keybindings?: { command: string }[]
    menus?: Record<string, { command?: string; submenu?: string }[]>
    [key: string]: unknown
  }
  [key: string]: unknown
}

/** Pure manifest transform; exported for tests. */
export function manifest(input: Manifest, cfg: Config = config): Manifest {
  const drop = removed(cfg)
  const keep = (item: { command?: string }) => !item.command || !drop.has(item.command)
  const contributes = input.contributes && {
    ...input.contributes,
    ...(input.contributes.commands && { commands: input.contributes.commands.filter(keep) }),
    ...(input.contributes.keybindings && { keybindings: input.contributes.keybindings.filter(keep) }),
    ...(input.contributes.menus && {
      menus: Object.fromEntries(Object.entries(input.contributes.menus).map(([key, list]) => [key, list.filter(keep)])),
    }),
  }
  const next = {
    ...input,
    publisher: cfg.identity.publisher,
    name: cfg.identity.name,
    displayName: cfg.identity.displayName,
    ...(contributes && { contributes }),
  }
  return JSON.parse(rename(JSON.stringify(next), cfg)) as Manifest
}

function files(dir: string): string[] {
  if (!existsSync(dir)) return []
  return readdirSync(dir).flatMap((item) => {
    const full = path.join(dir, item)
    if (statSync(full).isDirectory()) return files(full)
    return full.endsWith(".js") ? [full] : []
  })
}

/** Tracked files the transform rewrites; each is backed up as <file>.upstream and restored after packaging. */
function tracked(dir: string) {
  const nls = readdirSync(dir).filter((item) => /^package\.nls(\..+)?\.json$/.test(item))
  return [path.join(dir, "package.json"), ...nls.map((item) => path.join(dir, item))]
}

export function apply(dir: string, cfg: Config = config) {
  for (const file of tracked(dir)) {
    const backup = `${file}.upstream`
    const transform = (source: string) =>
      file.endsWith("package.json") ? JSON.stringify(manifest(JSON.parse(source) as Manifest, cfg), null, 2) + "\n" : rename(source, cfg)
    const current = readFileSync(file, "utf8")
    // A backup is reused only when the file still holds exactly what it produced (an interrupted build).
    // Otherwise the file is the newer original (a version bump, an edit, a stale backup) and is backed up anew.
    const kept = existsSync(backup) && transform(readFileSync(backup, "utf8")) === current
    if (!kept) copyFileSync(file, backup)
    writeFileSync(file, transform(readFileSync(backup, "utf8")))
  }
  // dist/ is build output, regenerated by every build: rewritten in place.
  for (const file of files(path.join(dir, "dist"))) {
    const text = readFileSync(file, "utf8")
    const next = rename(text, cfg)
    if (next !== text) writeFileSync(file, next)
  }
}

export function restore(dir: string) {
  for (const file of tracked(dir)) if (existsSync(`${file}.upstream`)) renameSync(`${file}.upstream`, file)
}

if (import.meta.main) {
  const dir = process.argv[2]
  if (!dir) throw new Error("usage: bun script/identity.ts <extension-dir> [--restore]")
  if (process.argv.includes("--restore")) restore(dir)
  else apply(dir)
}
